END_PAGE = 221  # საძიებელი და ნიშნების ცხრილი აღარ შედის


def page_text(pdf: Path, first: int, last: int) -> str:
    out = subprocess.run(
        ["pdftotext", "-f", str(first), "-l", str(last), str(pdf), "-"],
        capture_output=True, text=True, check=True,
    ).stdout
    # გავწმინდოთ: ზედმეტი ცარიელი ხაზები, გვერდის გამყოფები
    out = out.replace("\f", "\n")
    out = re.sub(r"\n{3,}", "\n\n", out)
    # InDesign-ის რბილი გადატანის ნიშნები
    out = out.replace("\u00ad", "")
    return out.strip()


def main():
    chunks = []
    for i, (ch, ch_title, sec, sec_title, start) in enumerate(TOC):
        end = (TOC[i + 1][4] - 1) if i + 1 < len(TOC) else END_PAGE
        text = page_text(PDF, start, end)
        chunks.append({
            "id": f"ch{ch}-{sec}",
            "chapter": ch,
            "chapter_title": ch_title,
            "section": sec,
            "section_title": sec_title,
            "page_start": start,
            "page_end": end,
            "text": text,
        })
        print(f"ch{ch} [{sec}] {sec_title}  (გვ. {start}-{end}, {len(text)} სიმბოლო)")

    OUT.write_text(json.dumps(chunks, ensure_ascii=False, indent=1), encoding="utf-8")
    total = sum(len(c["text"]) for c in chunks)
    print(f"\nსულ: {len(chunks)} სექცია, {total:,} სიმბოლო → {OUT}")


if __name__ == "__main__":
    main()
